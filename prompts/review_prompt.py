def build_review_prompt(level_type: str, level_design: str) -> str:
    """根据关卡类型构建评审 Prompt"""
    dimensions = SCORING_DIMENSIONS.get(level_type, SCORING_DIMENSIONS["stealth"])

    # 构建评分维度文本
    dimension_text = ""
    for i, (name, max_score, desc) in enumerate(dimensions, 1):
        dimension_text += f"{i}. **{name}**（{max_score} 分）：{desc}\n"

    total_score = sum(ms for _, ms, _ in dimensions)

    return f"""你是一位资深游戏关卡评审专家，专门评审 2D 游戏关卡设计方案。请你对以下关卡方案进行严格、专业的评审。

## 评分维度与标准

{dimension_text}

## 评审要求

1. **总分计算**：对每个维度分别打分，并给出总分（满分 {total_score} 分）。
2. **分项评分表格**：用 Markdown 表格列出每个维度的得分和简要评语。
3. **主要问题分析**：指出当前方案中存在的 3-5 个最突出的问题，每个问题需要具体说明问题所在，不能只说"不够好"。
4. **优化建议**：针对每个问题给出具体的、可执行的优化建议。每条建议要说明"改什么"和"为什么这样改"。
5. **作品集适合度**：评估该方案是否适合放入游戏策划作品集（是/否/部分适合），并给出理由。
6. **后续完善方向**：给出 2-3 个该方案可以继续深化的方向。

## 被评审的关卡方案

{level_design}

请直接输出评审结果，使用 Markdown 格式。"""
