"""
2D 潜入关卡 Prompt —— 重点关注路线、敌人巡逻、风险收益
"""

from prompts.base_prompt import BASE_LEVEL_STRUCTURE


def build_stealth_prompt(user_input: dict) -> str:
    """构建 2D 潜入关卡的生成 Prompt"""
    return f"""你是一名资深 2D 潜入类游戏策划，现在需要为以下关卡需求设计一份专业的关卡方案。

## 用户需求
- 游戏类型：{user_input.get('game_type', '2D 潜入')}
- 关卡场景：{user_input.get('scene', '城堡')}
- 玩家目标：{user_input.get('goal', '营救囚犯')}
- 关卡难度：{user_input.get('difficulty', '中等')}
- 敌人类型：{user_input.get('enemy_types', '巡逻兵、弓箭手')}
- 核心机制：{user_input.get('core_mechanics', '敌人巡逻、钥匙开门、隐藏路线')}
- 美术风格：{user_input.get('art_style', '像素风')}
- 预计游玩时长：{user_input.get('play_time', '3-5 分钟')}

## 潜入关卡设计重点
作为 2D 潜入关卡，你必须特别关注以下设计要素：

1. **安全路线设计**：为玩家设计至少一条安全通关路线。沿线说明哪里可以躲避敌人，哪里有掩体，敌人视野盲区在哪里。
2. **危险路线设计**：设计至少一条高风险高回报路线。说明这条路线的危险点在哪里，玩家需要付出什么代价，能获得什么额外收益。
3. **隐藏路线设计**：设计至少一条需要玩家探索才能发现的隐藏路线。说明发现条件、路线特点和独特奖励。
4. **敌人巡逻逻辑**：详细说明每个敌人的巡逻路径、视野范围、警戒状态变化、以及被发现后的追击行为。
5. **掩体与遮蔽物分布**：描述关卡中的掩体（木箱、墙壁、阴影等）的分布位置和使用策略。
6. **警报机制**：说明警报触发条件、警报等级、警报后的敌人行为变化，以及玩家如何解除警报。
7. **风险收益关系**：明确每条路线的风险和收益对比，让路线选择成为有意义的决策。

{BASE_LEVEL_STRUCTURE}

请直接输出关卡方案，不要额外解释。"""
