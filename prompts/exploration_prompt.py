"""
2D 探索冒险关卡 Prompt —— 重点关注区域连接、探索奖励、环境叙事
"""

from prompts.base_prompt import BASE_LEVEL_STRUCTURE


def build_exploration_prompt(user_input: dict) -> str:
    """构建 2D 探索冒险关卡的生成 Prompt"""
    return f"""你是一名资深 2D 探索冒险类游戏策划，现在需要为以下关卡需求设计一份专业的关卡方案。

## 用户需求
- 游戏类型：{user_input.get('game_type', '2D 探索冒险')}
- 关卡场景：{user_input.get('scene', '废弃古城')}
- 玩家目标：{user_input.get('goal', '探索古城、收集遗物、揭开秘密')}
- 关卡难度：{user_input.get('difficulty', '中等')}
- 敌人/障碍类型：{user_input.get('enemy_types', '野生动物、古代守卫、环境陷阱')}
- 核心机制：{user_input.get('core_mechanics', '地图解锁、能力获取、多区域连接')}
- 美术风格：{user_input.get('art_style', '像素风')}
- 预计游玩时长：{user_input.get('play_time', '5-10 分钟')}

## 探索冒险关卡设计重点
作为 2D 探索冒险关卡，你必须特别关注以下设计要素：

1. **区域连接设计**：描述关卡的多个区域（至少 3 个），说明区域之间的连接方式——直接通道、需要特定能力解锁、单向通道、传送点等。画出区域的逻辑连接图。
2. **探索路线设计**：设计多条探索路线——主线推进路线、分支探索路线、回头探索路线。说明每条路线的吸引力和回报。
3. **隐藏奖励分布**：在关卡各处放置隐藏奖励（收集品、道具、强化材料、背景故事碎片等）。说明藏匿方式和发现条件。
4. **支线目标**：设计 1-2 个支线目标，说明触发条件、完成方式和奖励。支线目标应与主线目标形成补充。
5. **环境叙事**：通过场景中的视觉元素（壁画、残骸、遗物等）讲述世界背景故事。说明哪些场景元素承载叙事功能。
6. **回报机制**：设计多层回报——探索小区域给与即时奖励，完成支线给与中等奖励，完成主要目标给与重大奖励。让玩家时刻感受到探索的价值。
7. **玩家探索动机**：说明关卡如何激发玩家的探索欲望——好奇心驱动（"那个门后面是什么"）、奖励驱动（"那里有个宝箱"）、叙事驱动（"我想知道这里发生了什么"）。

{BASE_LEVEL_STRUCTURE}

请直接输出关卡方案，不要额外解释。"""
