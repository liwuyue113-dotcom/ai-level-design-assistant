"""
2D 解谜关卡 Prompt —— 重点关注谜题目标、机关设计、信息提示
"""

from prompts.base_prompt import BASE_LEVEL_STRUCTURE


def build_puzzle_prompt(user_input: dict) -> str:
    """构建 2D 解谜关卡的生成 Prompt"""
    return f"""你是一名资深 2D 解谜类游戏策划，现在需要为以下关卡需求设计一份专业的关卡方案。

## 用户需求
- 游戏类型：{user_input.get('game_type', '2D 解谜')}
- 关卡场景：{user_input.get('scene', '古代神殿')}
- 玩家目标：{user_input.get('goal', '解开封印、打开密室')}
- 关卡难度：{user_input.get('difficulty', '中等')}
- 障碍/机关类型：{user_input.get('enemy_types', '压力板、可移动方块、光束机关')}
- 核心机制：{user_input.get('core_mechanics', '推箱子、钥匙开门、机关连锁')}
- 美术风格：{user_input.get('art_style', '像素风')}
- 预计游玩时长：{user_input.get('play_time', '5-8 分钟')}

## 解谜关卡设计重点
作为 2D 解谜关卡，你必须特别关注以下设计要素：

1. **谜题目标**：明确每个谜题的最终目标是什么（开门、激活装置、获取道具等），目标必须直观可理解。
2. **机关设计**：详细描述每种机关的类型、触发条件、效果和反馈。机关之间的关系（串联、并联、互斥）要清楚说明。
3. **信息提示系统**：说明玩家如何获取解谜线索——环境提示、视觉引导、文字/符号提示、NPC对话等。提示的层级（直接提示→间接提示→隐藏提示）。
4. **钥匙与门系统**：如果有钥匙-门机制，详细说明钥匙的获取方式、对应关系和使用逻辑。
5. **解谜步骤设计**：将每个谜题拆解为 2-4 个解谜步骤，说明每一步的玩家操作和预期结果。
6. **错误尝试反馈**：描述玩家做出错误操作时的反馈——是重置谜题、给出提示、还是允许继续尝试。确保玩家不会因为错误操作而陷入死局。
7. **谜题难度递进**：说明多个谜题之间的难度递进关系——从简单教学到复杂组合，每个谜题引入什么新概念。

{BASE_LEVEL_STRUCTURE}

请直接输出关卡方案，不要额外解释。"""
