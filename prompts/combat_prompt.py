"""
2D 动作战斗关卡 Prompt —— 重点关注战斗空间、敌人波次、战斗节奏
"""

from prompts.base_prompt import BASE_LEVEL_STRUCTURE


def build_combat_prompt(user_input: dict) -> str:
    """构建 2D 动作战斗关卡的生成 Prompt"""
    return f"""你是一名资深 2D 动作战斗类游戏策划，现在需要为以下关卡需求设计一份专业的关卡方案。

## 用户需求
- 游戏类型：{user_input.get('game_type', '2D 动作战斗')}
- 关卡场景：{user_input.get('scene', '角斗场/要塞')}
- 玩家目标：{user_input.get('goal', '击败所有敌人、击败 Boss')}
- 关卡难度：{user_input.get('difficulty', '中等')}
- 敌人类型：{user_input.get('enemy_types', '近战兵、远程射手、精英敌人、Boss')}
- 核心机制：{user_input.get('core_mechanics', '连击系统、闪避、技能释放、处决')}
- 美术风格：{user_input.get('art_style', '像素风')}
- 预计游玩时长：{user_input.get('play_time', '3-5 分钟')}

## 动作战斗关卡设计重点
作为 2D 动作战斗关卡，你必须特别关注以下设计要素：

1. **战斗空间设计**：描述战斗空间的大小、形状、高度差。说明空间如何支持玩家走位——哪里可以拉扯敌人，哪里适合群攻，哪里有死角。
2. **敌人波次设计**：将敌人出场分为若干波次，说明每波的敌人类型、数量、出场位置和出场时机。
3. **敌人组合策略**：说明不同敌人类型的搭配逻辑——近战牵制+远程输出、高速骚扰+重击压制等组合。让每波敌人组合产生不同的战斗策略需求。
4. **补给配置**：描述生命恢复、技能充能等补给品的位置和出现时机。补给不应过于频繁，但要在关键节点提供。
5. **掩体与走位要素**：描述战场中的可利用地形——高台、障碍物、可破坏物体等，以及它们对战斗策略的影响。
6. **Boss/精英敌人设计**：如果关卡包含 Boss 或精英敌人，请描述其攻击模式、阶段变化、弱点和应对策略。
7. **战斗节奏变化**：描述整场战斗的节奏——开局试探→第一波压制→喘息补给→多波围攻→Boss 战高潮→收尾。

{BASE_LEVEL_STRUCTURE}

请直接输出关卡方案，不要额外解释。"""
