"""
2D 平台跳跃关卡 Prompt —— 重点关注平台布局、跳跃节奏、难度曲线
"""

from prompts.base_prompt import BASE_LEVEL_STRUCTURE


def build_platformer_prompt(user_input: dict) -> str:
    """构建 2D 平台跳跃关卡的生成 Prompt"""
    return f"""你是一名资深 2D 平台跳跃类游戏策划，现在需要为以下关卡需求设计一份专业的关卡方案。

## 用户需求
- 游戏类型：{user_input.get('game_type', '2D 平台跳跃')}
- 关卡场景：{user_input.get('scene', '森林遗迹')}
- 玩家目标：{user_input.get('goal', '到达终点')}
- 关卡难度：{user_input.get('difficulty', '中等')}
- 敌人/障碍类型：{user_input.get('enemy_types', '移动平台、尖刺、落石')}
- 核心机制：{user_input.get('core_mechanics', '二段跳、冲刺、蹬墙跳')}
- 美术风格：{user_input.get('art_style', '像素风')}
- 预计游玩时长：{user_input.get('play_time', '3-5 分钟')}

## 平台跳跃关卡设计重点
作为 2D 平台跳跃关卡，你必须特别关注以下设计要素：

1. **平台布局**：描述平台的类型（固定/移动/消失/弹跳）、高度差、间距和排列方式。说明不同难度区域平台密度的变化。
2. **跳跃节奏设计**：设计玩家的跳跃节奏曲线——哪些区域是快速连续跳跃，哪些区域需要停顿观察，哪些区域需要精准操作。
3. **陷阱配置**：详细说明尖刺、落石、火焰、裂缝等陷阱的位置、触发方式和躲避方法。
4. **检查点位置**：合理设置检查点（复活点），说明每个检查点的位置、间距和设计理由。确保死亡后不会让玩家倒退太远。
5. **难度曲线**：描述关卡从开始到结束的难度变化——教学区、热身区、挑战区、高潮区、收尾区。
6. **玩家操作训练**：说明关卡如何逐步引入新机制并让玩家练习，如何通过关卡设计自然地教会玩家使用二段跳、冲刺等操作。
7. **失败后的重试体验**：描述玩家死亡后的体验——复活速度、失去的进度、是否需要重新挑战某些段落。

{BASE_LEVEL_STRUCTURE}

请直接输出关卡方案，不要额外解释。"""
